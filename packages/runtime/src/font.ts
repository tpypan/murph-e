export const GLYPH_W = 8
export const GLYPH_H = 8

/** Each glyph is 7 row bitmasks (bit 6 = leftmost column). */
export const GLYPHS: Map<string, Uint8Array> = new Map()
for (const [ch, art] of Object.entries(RAW)) {
  const rows = art.split('\n')
  const bits = new Uint8Array(7)
  for (let r = 0; r < 7; r++) {
    const row = rows[r] ?? ''
    let mask = 0
    for (let c = 0; c < 7; c++) if (row[c] === '#') mask |= 1 << (6 - c)
    bits[r] = mask
  }
  GLYPHS.set(ch, bits)
}
